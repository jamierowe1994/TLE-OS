export type FindingLevel = "blocker" | "query" | "ok";

export type Finding = {
  checkId: CheckId;
  level: FindingLevel;
  /** One sentence a person can act on. Never "see attached". */
  message: string;
  /** What the model read it from, so Kirstie can go and look at the same page. */
  documentName?: string;
  /** The date it found, where the check is a date check. ISO. */
  foundDate?: string | null;
  /**
   * The reader was offline or busy when this file came up (22 Oct 2026), so
   * this line stands in for a read that has not happened yet. lib/plc-reread
   * reads the file again once the API answers and replaces it.
   */
  waiting?: boolean;
  /** How many times a waiting file met a busy reader (an offline one is not counted). */
  tries?: number;
};

/**
 * A document in the pack.
 *
 * `key` is the R2 object key and `url` is the authenticated route that serves
 * it. Both are kept because they answer different questions: the scan needs
 * the key to fetch the bytes server-side, and the screen needs the URL to put
 * it behind a link. Deriving one from the other at the point of use is how a
 * raw bucket path ends up in page HTML.
 */
export type PlcDocument = {
  checkId: CheckId;
  name: string;
  key: string;
  url: string;
  addedAt: string;
  /** Who attached it. A pack is evidence, and evidence has a chain. */
  addedBy: string;
  /**
   * True when the bytes were never stored - a name standing in for a file on
   * an environment with no bucket attached.
   *
   * It exists so that a walkthrough on a laptop can reach the end of the
   * wizard without the screen ever implying a document is on file when it is
   * not. Anything showing a pack must show this, and the scan reports it as
   * unread rather than skipping it quietly.
   */
  placeholder?: boolean;
  /** What the reader made of the file when it was dropped. */
  read?: FileRead | null;
  /** SHA-256 of the bytes, so the same file is never on a pack twice (7 Oct 2026). */
  hash?: string;
  /**
   * Other checks this one document answers (Michael, 7 Oct 2026): a Legal for
   * Landlords reference report carries the tenant's ID, Right to Rent and AML,
   * so filed under Tenant checks it ticks Right to Rent too.
   */
  covers?: CheckId[];
  /** Brought in from the home's Documents tab rather than uploaded on the pack (8 Oct 2026). */
  fromFile?: boolean;
  /**
   * What the agent says it is, for a file under Anything else (James, 16 Oct
   * 2026 call: "title deeds" rather than a scan called IMG_4432.pdf). Shown
   * in place of the file name to compliance and used as its name in Propoly.
   */
  label?: string;
};

